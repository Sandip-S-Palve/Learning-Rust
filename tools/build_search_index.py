#!/usr/bin/env python3
"""Build assets/search-index.js from the h2/h3 headings of every chapter page.

Run from the course root after writing or editing chapters:
    python3 tools/build_search_index.py

The index is a plain script (window.SEARCH_INDEX = [...]) so search also works
when the site is opened from file://, where fetch() is blocked.
"""
import html
import json
import re
from html.parser import HTMLParser
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def slugify(text: str) -> str:
    # Must match slugify() in assets/app.js so section links resolve.
    s = re.sub(r"[^\w\s-]", "", text.lower()).strip()
    return (re.sub(r"\s+", "-", s)[:60]) or "section"


class Collector(HTMLParser):
    def __init__(self):
        super().__init__()
        self.title = ""
        self.sections = []  # (id, heading, text)
        self._in = None
        self._buf = []
        self._id = None
        self._para = []
        self._skip = 0

    def handle_starttag(self, tag, attrs):
        a = dict(attrs)
        if tag in ("script", "style", "pre", "svg"):
            self._skip += 1
        if tag in ("h1", "h2", "h3"):
            self._in, self._buf, self._id = tag, [], a.get("id")

    def handle_endtag(self, tag):
        if tag in ("script", "style", "pre", "svg"):
            self._skip = max(0, self._skip - 1)
        if tag == self._in:
            text = " ".join("".join(self._buf).split())
            if tag == "h1":
                self.title = text
            else:
                self.sections.append([self._id or slugify(text), text, []])
            self._in = None

    def handle_data(self, data):
        if self._in:
            self._buf.append(data)
        elif not self._skip and self.sections:
            words = self.sections[-1][2]
            if len(words) < 40:
                words.extend(data.split())


def main():
    entries = []
    seen_ids = {}
    for page in sorted((ROOT / "chapters").glob("*.html")):
        c = Collector()
        c.feed(page.read_text(encoding="utf-8"))
        seen_ids.clear()
        for sid, heading, words in c.sections:
            # De-duplicate ids the same way app.js does (base, base-2, base-3…)
            n = seen_ids.get(sid, 0) + 1
            seen_ids[sid] = n
            anchor = sid if n == 1 else f"{sid}-{n}"
            entries.append({
                "heading": html.unescape(heading),
                "chapter": c.title or page.stem,
                "url": f"chapters/{page.name}#{anchor}",
                "text": " ".join(words[:40]),
            })
    out = ROOT / "assets" / "search-index.js"
    out.write_text(
        "/* Generated by tools/build_search_index.py — do not edit by hand. */\n"
        "window.SEARCH_INDEX = " + json.dumps(entries, ensure_ascii=False, indent=0) + ";\n",
        encoding="utf-8",
    )
    print(f"Wrote {len(entries)} sections to {out.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
